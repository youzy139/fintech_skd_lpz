import { expect, test } from '@playwright/test'

test('管理员可以复核市场证据并完成真实两日回放', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '创建首位管理员' })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('login-desktop.png'), fullPage: true })
  await page.getByLabel('初始化凭据').fill('e2e-only-setup-code')
  await page.getByLabel('用户名', { exact: true }).fill('e2e-admin')
  await page.getByLabel('密码', { exact: true }).fill('e2e-only-password-123')
  const timings: Record<string, number> = {}
  const landingStarted = Date.now()
  await page.getByRole('button', { name: '创建并进入' }).click()
  await expect(page.getByText('从一个更清晰的视角，观察市场。')).toBeVisible()
  timings.landing_after_bootstrap_ms = Date.now() - landingStarted
  await page.screenshot({ path: test.info().outputPath('home-desktop.png'), fullPage: true })
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
  await expect(page.locator('.account-bar')).toBeInViewport({ ratio: 1 })
  expect(await page.locator('.account-bar').evaluate(element => getComputedStyle(element).position)).toBe('fixed')
  expect(await page.locator('.account-bar').evaluate(element => element.getBoundingClientRect().top)).toBe(0)
  await page.evaluate(() => window.scrollTo(0, 0))
  const workspaceStarted = Date.now()
  await page.getByRole('button', { name: /进入市场工作台/ }).click()
  await expect(page.getByRole('heading', { name: '市场总览' })).toBeVisible()
  timings.workspace_overview_ms = Date.now() - workspaceStarted
  await expect(page.locator('.chart canvas').first()).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('overview-desktop.png'), fullPage: true })
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出 CSV' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/500.csv$/)
  await page.getByRole('button', { name: '特征分析', exact: true }).click()
  await expect(page).toHaveURL(new RegExp('#/features$'))
  await page.reload()
  await expect(page.getByRole('heading', { name: '特征历史走势' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '计算与来源' })).toBeVisible()
  const featureValues = await (await page.request.get('/api/features/latest')).json()
  expect(featureValues.features).toEqual((await (await page.request.get('/api/regimes/latest')).json()).features)
  const metadata = await (await page.request.get('/api/features/metadata')).json()
  expect(metadata.feature_contract.feature_version).toMatch(/^features-[a-f0-9]{64}$/)
  expect(metadata.feature_contract.features.filter((item: { model_input: boolean }) => item.model_input)).toHaveLength(4)
  await page.getByText('查看版本与输入摘要', { exact: true }).click()
  await expect(page.getByText(metadata.input_version, { exact: true })).toBeVisible()
  await page.getByLabel('历史特征').selectOption('momentum')
  await expect(page.locator('.chart canvas').first()).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('features-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: '市场总览', exact: true }).click()
  await page.goBack()
  await expect(page.getByRole('heading', { name: '特征历史走势' })).toBeVisible()

  await page.getByRole('button', { name: /状态分析/ }).click()
  const stateResponse = await page.request.get('/api/regimes/latest')
  expect(stateResponse.ok()).toBe(true)
  const latestState = await stateResponse.json()
  expect(latestState.regime_identity).toBe('centroid-alignment-v1')
  expect(latestState.model_version).toMatch(/^walk-forward-aligned-v1-/)
  expect(latestState.label).toContain(`C${latestState.regime_id}`)
  await expect(page.getByText('状态特征热力图')).toBeVisible()
  await expect(page.locator('.chart canvas').first()).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('regimes-desktop.png'), fullPage: true })

  await page.getByRole('button', { name: /预警中心/ }).click()
  await page.getByRole('button', { name: '查看证据' }).first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog').getByText('训练数据截至', { exact: true })).toBeVisible()
  await expect(page.getByText(/截至前一状态日的公开背景/)).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.screenshot({ path: test.info().outputPath('alerts-desktop.png'), fullPage: true })

  const systemNavigation = page.getByRole('navigation', { name: '系统管理' })
  await systemNavigation.getByRole('button', { name: '系统监控' }).click()
  await expect(page).toHaveURL(new RegExp('#/system$'))
  await expect(page.getByRole('heading', { name: '系统运行监控' })).toBeVisible()
  await expect(page.getByText('整体状态：', { exact: false })).toBeVisible()
  await expect(page.getByRole('heading', { name: '热特征缓存' })).toBeVisible()
  await expect(page.getByText('Redis 热特征缓存未启用，读取已计算的特征快照。')).toBeVisible()
  await expect(page.getByText('进程内一级缓存')).toHaveCount(0)
  await page.screenshot({ path: test.info().outputPath('system-desktop.png'), fullPage: true })
  await systemNavigation.getByRole('button', { name: '审计记录' }).click()
  await expect(page).toHaveURL(new RegExp('#/audit$'))
  await expect(page.getByRole('heading', { name: '审计记录' })).toBeVisible()
  await expect(page.getByText('保留与对象归档')).toBeVisible()
  await expect(page.getByRole('cell', { name: '管理员初始化' })).toBeVisible()
  await systemNavigation.getByRole('button', { name: '账号权限' }).click()
  await expect(page).toHaveURL(new RegExp('#/accounts$'))
  await expect(page.getByRole('heading', { name: '账号权限', exact: true })).toBeVisible()
  await expect(page.getByText('e2e-admin（当前账号）')).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('accounts-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: '市场总览', exact: true }).click()
  await expect(page.getByRole('heading', { name: '市场总览' })).toBeVisible()

  await page.getByRole('button', { name: '历史回放', exact: true }).click()
  const assets = await page.request.get('/api/assets')
  const code = (await assets.json())[0].code
  const series = await page.request.get(`/api/assets/${code}/series?limit=2`)
  const points = (await series.json()).points
  await page.getByLabel('回放开始日期').fill(points[0].date)
  await page.getByLabel('回放结束日期').fill(points[1].date)
  await page.getByLabel('回放速度').selectOption('10')
  await expect(page.getByLabel('回放开始日期')).toHaveValue(points[0].date)
  await expect(page.getByLabel('回放结束日期')).toHaveValue(points[1].date)
  await page.getByRole('button', { name: '开始回放' }).click()
  await expect(page.getByText('已完成', { exact: true })).toBeVisible({ timeout: 120_000 })
  await expect(page.getByText('2 / 2 个交易日')).toBeVisible()
  await expect(page.getByText('结果推送已连接')).toBeVisible()
  const sessionResponse = await page.request.get('/api/replay/sessions/current')
  expect(sessionResponse.ok()).toBe(true)
  const session = await sessionResponse.json()
  expect(session.model_identity).toBe('centroid-alignment-v1')
  expect(session.lineage_status).toBe('pinned')
  expect(session.calculation_contract.model.training_window).toBe(756)
  expect(session.calculation_contract.feature_contract.feature_version).toBe(metadata.feature_contract.feature_version)
  await page.getByText('查看固定参数与版本', { exact: true }).click()
  await expect(page.getByText(session.calculation_contract.version, { exact: true })).toBeVisible()
  expect(session.latest_result.state.regime_identity).toBe('centroid-alignment-v1')
  await page.screenshot({ path: test.info().outputPath('replay-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: '数据中心', exact: true }).click()
  await expect(page.getByRole('heading', { name: '全部数据', exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('catalog-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '打开导航' }).click()
  await page.getByRole('button', { name: '市场总览', exact: true }).click()
  await expect(page.getByRole('button', { name: '打开导航' })).toHaveAttribute('aria-expanded', 'false')
  await expect.poll(() => page.locator('.sidebar').evaluate(element => element.getBoundingClientRect().right)).toBeLessThanOrEqual(0)
  await expect(page.getByRole('heading', { name: '市场总览', exact: true })).toBeVisible()
  await expect(page.locator('.chart canvas').first()).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('overview-mobile.png'), fullPage: true })
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
  await expect(page.locator('.account-bar')).toBeInViewport({ ratio: 1 })
  expect(await page.locator('.account-bar').evaluate(element => element.getBoundingClientRect().top)).toBe(0)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page.getByRole('heading', { name: '登录市场工作台' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('login-mobile.png'), fullPage: true })
  expect(errors).toEqual([])
  await test.info().attach('page-timings', { body: JSON.stringify(timings), contentType: 'application/json' })
  console.log('E2E_PERFORMANCE ' + JSON.stringify(timings))
})
